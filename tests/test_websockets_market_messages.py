@pytest.mark.parametrize("message", MARKET_MESSAGES)
def test_market_message_timestamp_and_local_timestamp(message: dict[str, Any]) -> None:
    before = datetime.now().astimezone()
    event = MARKET_EVENT_CLASSES[message["event_type"]](**message)
    after = datetime.now().astimezone()

    assert int(event.timestamp.timestamp() * 1000) == int(message["timestamp"])
    assert before <= event.local_timestamp <= after
    assert event.local_timestamp.tzinfo is not None
